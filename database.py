"""Base de datos del Sistema Logístico usando Supabase PostgreSQL."""

import hashlib
import streamlit as st
from sqlalchemy import text
from sqlalchemy.exc import IntegrityError, SQLAlchemyError


def get_connection():
    return st.connection("postgresql", type="sql")


def hash_password(password):
    # Conserva compatibilidad con las contraseñas guardadas con SHA-256.
    return hashlib.sha256(password.encode("utf-8")).hexdigest()


def init_db():
    """Crea las tablas si todavía no existen."""
    conn = get_connection()

    with conn.session as session:
        session.execute(text("""
            CREATE TABLE IF NOT EXISTS usuarios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL
            )
        """))

        session.execute(text("""
            CREATE TABLE IF NOT EXISTS productos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                codigo TEXT UNIQUE NOT NULL,
                nombre TEXT NOT NULL,
                categoria TEXT,
                stock INTEGER NOT NULL DEFAULT 0,
                stock_minimo INTEGER NOT NULL DEFAULT 5,
                precio NUMERIC(12, 2) NOT NULL DEFAULT 0
            )
        """))

        session.execute(text("""
            CREATE TABLE IF NOT EXISTS movimientos (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                producto_id BIGINT NOT NULL REFERENCES productos(id),
                tipo TEXT NOT NULL CHECK (tipo IN ('entrada', 'salida')),
                cantidad INTEGER NOT NULL CHECK (cantidad > 0),
                fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """))

        session.commit()


def crear_usuario(username, password):
    """Devuelve (éxito, mensaje)."""
    username = username.strip()

    if not username or not password:
        return False, "Completa el usuario y la contraseña."

    conn = get_connection()

    try:
        with conn.session as session:
            session.execute(
                text("""
                    INSERT INTO usuarios (username, password)
                    VALUES (:username, :password)
                """),
                {
                    "username": username,
                    "password": hash_password(password),
                },
            )
            session.commit()

        return True, "Cuenta creada correctamente. Ya puedes iniciar sesión."

    except IntegrityError:
        return False, "Ese nombre de usuario ya existe."

    except SQLAlchemyError:
        st.error(
            "No se pudo guardar la cuenta en la base de datos. "
            "Revisa la conexión y los registros de la aplicación."
        )
        return False, "No se pudo crear la cuenta."


def validar_usuario(username, password):
    """Comprueba las credenciales sin evaluar un DataFrame como booleano."""
    conn = get_connection()

    try:
        with conn.session as session:
            resultado = session.execute(
                text("""
                    SELECT id
                    FROM usuarios
                    WHERE username = :username AND password = :password
                    LIMIT 1
                """),
                {
                    "username": username.strip(),
                    "password": hash_password(password),
                },
            )
            fila = resultado.fetchone()

        return fila is not None

    except SQLAlchemyError:
        st.error(
            "No se pudo consultar el usuario. "
            "Revisa la conexión con PostgreSQL."
        )
        return False


def agregar_producto(codigo, nombre, categoria, stock_minimo, precio):
    conn = get_connection()

    try:
        with conn.session as session:
            session.execute(
                text("""
                    INSERT INTO productos
                        (codigo, nombre, categoria, stock_minimo, precio)
                    VALUES
                        (:codigo, :nombre, :categoria, :stock_minimo, :precio)
                """),
                {
                    "codigo": codigo.strip(),
                    "nombre": nombre.strip(),
                    "categoria": categoria.strip(),
                    "stock_minimo": stock_minimo,
                    "precio": precio,
                },
            )
            session.commit()

        return True, f"Producto '{nombre}' registrado correctamente."

    except IntegrityError:
        return False, "Ya existe un producto con ese código."

    except SQLAlchemyError:
        st.error("No se pudo guardar el producto en PostgreSQL.")
        return False, "Error al registrar el producto."


def listar_productos():
    conn = get_connection()

    with conn.session as session:
        resultado = session.execute(text("""
            SELECT id, codigo, nombre, categoria, stock,
                   stock_minimo, precio
            FROM productos
            ORDER BY nombre
        """))
        return [dict(fila) for fila in resultado.mappings().all()]


def registrar_movimiento(producto_id, tipo, cantidad):
    if tipo not in ("entrada", "salida") or cantidad <= 0:
        return False, "El tipo o la cantidad no son válidos."

    conn = get_connection()

    try:
        with conn.session as session:
            fila = session.execute(
                text("""
                    SELECT stock
                    FROM productos
                    WHERE id = :id
                    FOR UPDATE
                """),
                {"id": producto_id},
            ).fetchone()

            if fila is None:
                return False, "Producto no encontrado."

            stock_actual = fila[0]

            if tipo == "salida" and stock_actual < cantidad:
                return False, f"Stock insuficiente. Hay {stock_actual} unidades."

            nuevo_stock = (
                stock_actual + cantidad
                if tipo == "entrada"
                else stock_actual - cantidad
            )

            session.execute(
                text("""
                    INSERT INTO movimientos (producto_id, tipo, cantidad)
                    VALUES (:producto_id, :tipo, :cantidad)
                """),
                {
                    "producto_id": producto_id,
                    "tipo": tipo,
                    "cantidad": cantidad,
                },
            )

            session.execute(
                text("""
                    UPDATE productos
                    SET stock = :stock
                    WHERE id = :id
                """),
                {"stock": nuevo_stock, "id": producto_id},
            )

            session.commit()

        return True, "Movimiento registrado correctamente."

    except SQLAlchemyError:
        st.error("No se pudo guardar el movimiento en PostgreSQL.")
        return False, "Error al registrar el movimiento."


def productos_bajo_stock():
    conn = get_connection()

    with conn.session as session:
        resultado = session.execute(text("""
            SELECT id, codigo, nombre, categoria, stock,
                   stock_minimo, precio
            FROM productos
            WHERE stock <= stock_minimo
            ORDER BY nombre
        """))
        return [dict(fila) for fila in resultado.mappings().all()]


def historial_movimientos():
    conn = get_connection()

    with conn.session as session:
        resultado = session.execute(text("""
            SELECT m.id, p.nombre AS producto, m.tipo,
                   m.cantidad, m.fecha
            FROM movimientos m
            JOIN productos p ON p.id = m.producto_id
            ORDER BY m.fecha DESC, m.id DESC
            LIMIT 50
        """))
        return [dict(fila) for fila in resultado.mappings().all()]

